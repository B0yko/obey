#!/usr/bin/env python3
"""obey pre-commit check: the staged diff and the commit message against .obey/hooks/rules.json.

Generated by obey (https://github.com/B0yko/obey). Standard library only, Python 3.9+. Works with any agent and
with people. Install as git hooks:

    ln -s ../../.obey/pre-commit .git/hooks/pre-commit
    ln -s ../../.obey/pre-commit .git/hooks/commit-msg

or through the pre-commit framework (see the obey README). With a commit-message file argument it checks the
message; without one it checks the staged changes. Exit code 1 blocks the commit. An internal error (the engine
cannot be loaded, a crash) allows the commit and says so on stderr, so a bug here can never lock you out of git.
"""

import os
import subprocess
import sys


def _find_root():
    """The project root: git's top level when it holds obey's files, else where this script really lives.

    Through the symlink install, __file__ is .git/hooks/pre-commit; its real path is <root>/.obey/pre-commit.
    """
    real = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
    try:
        out = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, timeout=10, check=False)
        top = out.stdout.decode("utf-8", "replace").strip() if out.returncode == 0 else ""
    except (OSError, subprocess.SubprocessError):
        top = ""
    for candidate in (top, real):
        if candidate and os.path.isfile(os.path.join(candidate, ".obey", "hooks", "rules.json")):
            return candidate
    return real


ROOT = _find_root()
sys.path.insert(0, os.path.join(ROOT, ".obey", "hooks"))

STAGED_TYPES = {
    "path_forbidden",
    "dependency_unchanged",
    "content_forbidden_added",
    "content_required_added",
    "file_naming",
    "path_required_with",
    "command_forbidden",
}


# Files `obey enforce` writes: they quote the rules and the engine's own code, so they are not checked against them.
OWN = (
    ".obey",
    ".claude/settings.json",
    ".codex/hooks.json",
    ".cursor/hooks.json",
    ".gemini/settings.json",
    ".github/hooks/obey.json",
    ".opencode/plugins/obey.ts",
)


def _git(*args):
    out = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, timeout=30, check=False)
    return out.stdout.decode("utf-8", "replace")


def main(argv):
    try:
        import json

        import obey_engine

        with open(os.path.join(ROOT, ".obey", "hooks", "rules.json"), encoding="utf-8") as fh:
            rules = json.load(fh)["rules"]
        message_file = next((a for a in argv[1:] if not a.startswith("-")), None)
        problems = []
        if message_file:
            with open(message_file, encoding="utf-8", errors="replace") as fh:
                message = "\n".join(line for line in fh.read().splitlines() if not line.startswith("#")).strip()
            run = {
                "events": [],
                "diff": "",
                "base_files": [],
                "commits": [{"sha": "staged", "message": message, "files": []}],
                "pushed_refs": [],
                "final_message": "",
            }
            selected = [r for r in rules if r["checker"]["type"] == "commit_message"]
        else:
            run = {
                "events": [],
                "diff": _git(
                    "diff", "--cached", "--no-color", "--no-ext-diff", "--", ".", *[":(exclude)" + p for p in OWN]
                ),
                "base_files": [p for p in _git("ls-files", "-z").split("\0") if p],
                "commits": [],
                "pushed_refs": [],
                "final_message": "",
            }
            selected = [r for r in rules if r["checker"]["type"] in STAGED_TYPES]
        for rule in selected:
            verdict = obey_engine.check(rule, run)
            if verdict["verdict"] == "violated":
                problems.append(obey_engine.reason(rule, verdict))
        if problems:
            sys.stderr.write("obey: commit blocked\n" + "".join("  - " + p + "\n" for p in problems))
            return 1
        return 0
    except Exception as exc:
        sys.stderr.write("obey pre-commit error, commit allowed: {}: {}\n".format(type(exc).__name__, exc))
        return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
