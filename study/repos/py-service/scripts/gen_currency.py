"""Generate src/ledgerline/generated/currency_codes.py.

Run `make gen` after changing CURRENCIES, then commit the regenerated module.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src" / "ledgerline" / "generated" / "currency_codes.py"

# (ISO 4217 code, number of minor-unit digits)
CURRENCIES: tuple[tuple[str, int], ...] = (
    ("AUD", 2),
    ("BHD", 3),
    ("CAD", 2),
    ("CHF", 2),
    ("CNY", 2),
    ("CZK", 2),
    ("DKK", 2),
    ("EUR", 2),
    ("GBP", 2),
    ("HKD", 2),
    ("HUF", 2),
    ("JPY", 0),
    ("KWD", 3),
    ("NOK", 2),
    ("NZD", 2),
    ("PLN", 2),
    ("SEK", 2),
    ("SGD", 2),
    ("UAH", 2),
    ("USD", 2),
    ("ZAR", 2),
)

HEADER = """\
# SPDX-License-Identifier: Apache-2.0
# Generated by scripts/gen_currency.py — do not edit.
\"\"\"ISO 4217 currency codes and their minor-unit digits.\"\"\"

from typing import Final

CURRENCY_MINOR_UNITS: Final[dict[str, int]] = {
"""


def render() -> str:
    """Return the full text of the generated module."""
    rows = "".join(f'    "{code}": {digits},\n' for code, digits in sorted(CURRENCIES))
    return HEADER + rows + "}\n"


def main() -> int:
    OUTPUT.write_text(render(), encoding="utf-8")
    sys.stdout.write(f"wrote {OUTPUT.name} ({len(CURRENCIES)} currencies)\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
